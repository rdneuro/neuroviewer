def user_config_path():
    """Location of the user config file (it may not exist)."""
    env = os.environ.get("NEUROVIEWER_CONFIG", "").strip()
    if env:
        return os.path.abspath(os.path.expanduser(env))
    if os.name == "nt":
        base = os.environ.get("APPDATA") or os.path.expanduser("~")
    else:
        base = os.environ.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")
    return os.path.join(base, "neuroviewer", "config.py")


def _apply_user_config():
    """Override the defaults above with the user file. Problems only print."""
    path = user_config_path()
    if not os.path.isfile(path):
        return
    try:
        values = runpy.run_path(path)
    except Exception as exc:  # noqa: BLE001
        print(f"[config] could not read {path}: {exc!r} -> defaults kept")
        return
    g = globals()
    changed, unknown = [], []
    for key, val in values.items():
        if not key.isupper():
            continue
        if key in g:
            if g[key] != val:
                changed.append(key)
            g[key] = val
        else:
            unknown.append(key)
    print(f"[config] {path}: {len(changed)} setting(s) differ from the defaults"
          + (f" ({', '.join(changed)})" if changed else ""))
    if unknown:
        print(f"[config] WARNING: unknown names ignored: {', '.join(unknown)}")


_apply_user_config()
